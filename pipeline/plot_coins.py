#!/usr/bin/env python3
"""
plot_coins.py — Per-coin (BTC vs ETH) breakdown charts from a single isolated run.

Reproduces the 7 per-coin charts that were previously generated by an internal
(uncommitted) script:

  08b_coin_A_liq_rates.png     — Paper vs HL liquidation rate, grouped bars
  08b_coin_B_winrate.png       — win rate by direction (Long/Short), grouped bars
  08b_coin_C_ev_dist.png       — EV-per-trade distribution (trader perspective)
  08b_coin_D_adverse_moves.png — worst-adverse-move distribution + bust threshold
  08b_coin_E_lp_delta.png      — LP-delta-per-trade distribution
  08b_coin_F_summary.png       — BTC vs ETH summary table
  08c_liq_by_coin.png          — daily Paper liquidation rate per coin (time series)

Reads paper_sim_trades.parquet from --sim-dir (default sim_flow_1.00) and the
liquidation threshold from --config. Writes PNGs into --charts-dir (default charts/).

Usage:
    python3 plot_coins.py
    python3 plot_coins.py --sim-dir sim_flow_1.00 --config paper_config.yaml --charts-dir charts
"""

from __future__ import annotations

import argparse
import logging
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import matplotlib.dates as mdates
import matplotlib.ticker
import numpy as np
import pandas as pd
import yaml

# BTC / ETH colours (approx. match the original charts)
COL = {"BTC": "#f0a04b", "ETH": "#8390e8"}
COL_LONG = "#4caf50"
COL_SHORT = "#e0554b"
COINS = ["BTC", "ETH"]
DAY_MS = 86_400_000

# HL max-leverage tier per coin (annotation only)
MAX_LEV = {"BTC": 40, "ETH": 25}


def signed_log10(x: np.ndarray) -> np.ndarray:
    """Signed log compression: sign(x) * log10(|x| + 1)."""
    return np.sign(x) * np.log10(np.abs(x) + 1.0)


def _save(fig, out: Path, name: str):
    path = out / name
    fig.savefig(path, bbox_inches="tight", dpi=130)
    plt.close(fig)
    logging.info("  %s", name)


def load(sim_dir: Path, cfg: dict) -> tuple[pd.DataFrame, float]:
    trades = pd.read_parquet(sim_dir / "paper_sim_trades.parquet")
    # some price/pnl columns arrive as decimal.Decimal — coerce to float
    for col in ("open_px", "close_px", "worst_adverse_px",
                "user_pnl_usd", "lp_balance_delta_usd"):
        if col in trades.columns:
            trades[col] = pd.to_numeric(trades[col], errors="coerce").astype(float)
    # valid = close price present (matches the original "valid trades only" filter)
    trades = trades[trades["close_px"].notna() & (trades["open_px"] > 0)].copy()
    trades["is_win"] = trades["user_pnl_usd"] > 0
    trades["adverse_pct"] = (
        (trades["worst_adverse_px"] - trades["open_px"]).abs() / trades["open_px"] * 100.0
    )
    leverage = float(cfg.get("paper_leverage", 1000))
    buffer_bps = float(cfg.get("bust_buffer_bps", 5))
    tolerance = 1.0 / leverage - buffer_bps / 10_000.0   # fractional
    threshold_pct = tolerance * 100.0                    # in %
    return trades, threshold_pct


def liq_rates(trades: pd.DataFrame) -> dict:
    return {c: 100.0 * trades.loc[trades.coin == c, "paper_was_liquidated"].mean()
            for c in COINS}


# ---------------------------------------------------------------------------
# A — Paper vs HL liquidation rate
# ---------------------------------------------------------------------------
def chart_A(trades, out, liq):
    fig, ax = plt.subplots(figsize=(9, 6))
    x = np.arange(len(COINS))
    w = 0.38
    paper = [100.0 * trades.loc[trades.coin == c, "paper_was_liquidated"].mean() for c in COINS]
    hl = [100.0 * trades.loc[trades.coin == c, "hl_was_liquidated"].mean() for c in COINS]
    for i, c in enumerate(COINS):
        ax.bar(x[i] - w / 2, paper[i], w, color=COL[c],
               label="Paper 1000x (5 bps buffer)" if i == 0 else None)
        ax.bar(x[i] + w / 2, hl[i], w, color=COL[c], alpha=0.55, hatch="//",
               edgecolor="black", label="HL real-world (max-lev trades)" if i == 0 else None)
        ax.text(x[i] - w / 2, paper[i] + 1, f"{paper[i]:.2f}%", ha="center", fontweight="bold")
        ax.text(x[i] + w / 2, hl[i] + 1, f"{hl[i]:.2f}%", ha="center", color="#555")
    ax.set_xticks(x); ax.set_xticklabels(COINS, fontsize=13)
    ax.set_ylabel("Liquidation rate (%)")
    ax.set_title("BTC vs ETH — Paper liq rate vs HL liq rate\n"
                 "ETH Paper liq > BTC despite lower HL liq: ETH max-lev trades have larger adverse moves\n"
                 f"(canonical liq rates: BTC {liq['BTC']:.1f}% / ETH {liq['ETH']:.1f}%)",
                 fontsize=10)
    ax.legend(loc="upper left"); ax.grid(axis="y", alpha=0.3)
    ax.yaxis.set_major_formatter(matplotlib.ticker.PercentFormatter(decimals=0))
    _save(fig, out, "08b_coin_A_liq_rates.png")


# ---------------------------------------------------------------------------
# B — win rate by direction
# ---------------------------------------------------------------------------
def chart_B(trades, out, liq):
    fig, ax = plt.subplots(figsize=(9, 6))
    x = np.arange(len(COINS))
    w = 0.38
    for i, c in enumerate(COINS):
        sub = trades[trades.coin == c]
        wl = 100.0 * sub.loc[sub.direction == "long", "is_win"].mean()
        ws = 100.0 * sub.loc[sub.direction == "short", "is_win"].mean()
        ax.bar(x[i] - w / 2, wl, w, color=COL_LONG, label="Long" if i == 0 else None)
        ax.bar(x[i] + w / 2, ws, w, color=COL_SHORT, label="Short" if i == 0 else None)
        ax.text(x[i] - w / 2, wl + 0.1, f"{wl:.1f}%", ha="center")
        ax.text(x[i] + w / 2, ws + 0.1, f"{ws:.1f}%", ha="center")
    ax.set_xticks(x); ax.set_xticklabels(COINS, fontsize=13)
    ax.set_ylabel("Win rate (%)")
    ax.set_title("BTC vs ETH — Paper win rate by direction\n"
                 "(% of valid trades where trader ended positive after impact scaling)\n"
                 f"(canonical liq rates: BTC {liq['BTC']:.1f}% / ETH {liq['ETH']:.1f}%)",
                 fontsize=10)
    ax.legend(loc="upper right"); ax.grid(axis="y", alpha=0.3)
    ax.yaxis.set_major_formatter(matplotlib.ticker.PercentFormatter(decimals=0))
    _save(fig, out, "08b_coin_B_winrate.png")


# ---------------------------------------------------------------------------
# C — EV-per-trade distribution (trader perspective)
# ---------------------------------------------------------------------------
def chart_C(trades, out, liq):
    fig, ax = plt.subplots(figsize=(13, 6.5))
    vals = {c: signed_log10(trades.loc[trades.coin == c, "user_pnl_usd"].values) for c in COINS}
    lo = min(v.min() for v in vals.values())
    hi = max(v.max() for v in vals.values())
    bins = np.linspace(lo, hi, 80)
    for c in COINS:
        mean_ev = trades.loc[trades.coin == c, "user_pnl_usd"].mean()
        ax.hist(vals[c], bins=bins, density=True, alpha=0.5, color=COL[c],
                label=f"{c}  (mean EV = ${mean_ev:.1f})")
    ax.axvline(0, color="black", lw=1.2, label="EV = $0")
    ax.set_xlabel("signed log₁₀(|EV|+1)   ←  loss  |  win  →")
    ax.set_ylabel("Density")
    ax.set_title("BTC vs ETH — EV per trade distribution (trader perspective, Paper mechanics)\n"
                 "Left of zero = trader lost money; Right = trader won\n"
                 f"(canonical liq rates: BTC {liq['BTC']:.1f}% / ETH {liq['ETH']:.1f}%)",
                 fontsize=10)
    ax.legend(loc="upper right"); ax.grid(alpha=0.25)
    _save(fig, out, "08b_coin_C_ev_dist.png")


# ---------------------------------------------------------------------------
# D — worst adverse move distribution + bust threshold
# ---------------------------------------------------------------------------
def chart_D(trades, out, threshold_pct):
    fig, ax = plt.subplots(figsize=(13, 6.5))
    # Full (unfiltered) adverse-move array per coin — used for the "% above
    # threshold", which must equal the liquidation rate (trades with a zero /
    # missing adverse move are NOT liquidated and must stay in the denominator).
    adv_full = {c: trades.loc[trades.coin == c, "adverse_pct"].values for c in COINS}
    # Positive-only subset, used solely for the log-scale histogram.
    adv_pos = {c: v[(v > 0) & np.isfinite(v)] for c, v in adv_full.items()}
    logvals = {c: np.log10(v) for c, v in adv_pos.items()}
    lo = min(v.min() for v in logvals.values())
    hi = max(v.max() for v in logvals.values())
    bins = np.linspace(lo, hi, 90)
    for c in COINS:
        p50 = np.median(adv_pos[c])
        # "% above threshold" is the Paper liquidation rate itself — computed on
        # ALL valid trades (the histogram's positive filter must NOT shrink the
        # denominator), so it agrees with Figure 2 (80.0% / 91.5%).
        above = 100.0 * trades.loc[trades.coin == c, "paper_was_liquidated"].mean()
        ax.hist(logvals[c], bins=bins, density=True, alpha=0.5, color=COL[c],
                label=f"{c}  p50={p50:.3f}% → {above:.1f}% above threshold")
    ax.axvline(np.log10(threshold_pct), color="black", lw=2, ls="--",
               label=f"Paper bust threshold = {threshold_pct:.2f}% adverse move")
    total = len(trades)
    ax.set_xlabel("log₁₀(worst adverse move %)   [Paper liquidation threshold shown]")
    ax.set_ylabel("Density")
    ax.set_title("KEY CHART — worst adverse move distribution by coin "
                 f"(valid trades, n={total/1e6:.1f}M)\n"
                 "Area to RIGHT of threshold → Paper liquidation\n"
                 "ETH trades are structurally more volatile (larger adverse moves) "
                 "→ higher Paper liq despite lower HL liq", fontsize=10)
    ax.legend(loc="upper left"); ax.grid(alpha=0.25)
    _save(fig, out, "08b_coin_D_adverse_moves.png")


