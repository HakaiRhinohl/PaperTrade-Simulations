# F — summary table
# ---------------------------------------------------------------------------
def chart_F(trades, out, liq):
    cols = ["Coin", "n trades", "HL max-lev", "Paper liq", "HL liq",
            "Paper liq L/S", "Win rate L/S", "EV/trade ($)", "LP Δ avg ($)", "Long/Short"]
    rows = []
    cell_colours = []
    for c in COINS:
        sub = trades[trades.coin == c]
        paper_liq = 100.0 * sub["paper_was_liquidated"].mean()
        hl_liq = 100.0 * sub["hl_was_liquidated"].mean()
        pl = 100.0 * sub.loc[sub.direction == "long", "paper_was_liquidated"].mean()
        ps = 100.0 * sub.loc[sub.direction == "short", "paper_was_liquidated"].mean()
        wl = 100.0 * sub.loc[sub.direction == "long", "is_win"].mean()
        ws = 100.0 * sub.loc[sub.direction == "short", "is_win"].mean()
        ev = sub["user_pnl_usd"].mean()
        lpd = sub["lp_balance_delta_usd"].mean()
        n_long = 100.0 * (sub.direction == "long").mean()
        rows.append([
            c, f"{len(sub):,}", f"{MAX_LEV[c]}x",
            f"{paper_liq:.2f}%", f"{hl_liq:.2f}%",
            f"L {pl:.1f}% / S {ps:.1f}%", f"L {wl:.1f}% / S {ws:.1f}%",
            f"${ev:.2f}", f"${lpd:.3f}", f"{n_long:.0f}% / {100 - n_long:.0f}%",
        ])
        base = COL[c]
        colours = ["#fff3e0" if c == "BTC" else "#e8eaf6"] + ["white"] * 2 + \
                  ["#fcd9a8", "#d7ead3"] + ["white"] * 5
        cell_colours.append(colours)

    fig, ax = plt.subplots(figsize=(15, 3))
    ax.axis("off")
    tbl = ax.table(cellText=rows, colLabels=cols, cellColours=cell_colours,
                   colColours=["#c5cfe0"] * len(cols), loc="center", cellLoc="center")
    tbl.auto_set_font_size(False); tbl.set_fontsize(10); tbl.scale(1, 2.2)
    ax.set_title("BTC vs ETH — Summary table  (valid trades only, Paper 1000x 5bps)\n"
                 f"(canonical liq rates: BTC {liq['BTC']:.1f}% / ETH {liq['ETH']:.1f}%)",
                 fontsize=11, fontweight="bold")
    _save(fig, out, "08b_coin_F_summary.png")


# ---------------------------------------------------------------------------
# 08c — daily Paper liquidation rate per coin (time series)
# ---------------------------------------------------------------------------
def chart_liq_by_coin(trades, out, liq):
    t = trades.copy()
    t["day"] = pd.to_datetime((t["close_time_ms"] // DAY_MS) * DAY_MS, unit="ms", utc=True)
    adl_days = sorted(t.loc[t.get("hl_was_adl", False) == True, "day"].unique()) \
        if "hl_was_adl" in t.columns else []

    fig, axes = plt.subplots(2, 1, figsize=(15, 9), sharex=True)
    for ax, c in zip(axes, COINS):
        sub = t[t.coin == c]
        daily = sub.groupby("day")["paper_was_liquidated"].mean() * 100.0
        ax.plot(daily.index, daily.values, color=COL[c], lw=1.5)
        ax.fill_between(daily.index, 0, daily.values, color=COL[c], alpha=0.12)
        avg = liq[c]
        ax.axhline(avg, color=COL[c], ls=":", lw=1)
        ax.text(daily.index[-1], avg, f" avg {avg:.1f}%", color=COL[c],
                va="center", fontsize=9)
        for d in adl_days:
            ax.axvspan(d, d + pd.Timedelta(days=1), color="#7b5ea8", alpha=0.18)
        ax.set_ylim(0, 105); ax.set_ylabel("% trades liquidated in Paper")
        ax.set_title(f"Daily Paper liquidation rate — {c}  "
                     f"(max lev: {MAX_LEV[c]}x, Paper 1000x, 5 bps buffer)", fontsize=12)
        ax.grid(alpha=0.25)
    axes[-1].xaxis.set_major_formatter(mdates.DateFormatter("%b %y"))
    fig.autofmt_xdate()
    _save(fig, out, "08c_liq_by_coin.png")


# ---------------------------------------------------------------------------
# Figure 4 — share of a winning trade kept after impact (deployed params)
# ---------------------------------------------------------------------------
def _scale(p, move):
    return ((1.0 - p["base_rate"]) /
            (1.0 + 1.0 / (move * p["rate_multiplier"])
             + p["reference_notional_usd"] / (move * p["position_multiplier"])))


def _retained(p, move, deadband):
    """Share of the raw win the trader keeps: impact scale on the deadband-net
    move, times the fraction of the move that survives the deadband."""
    net = move - deadband
    if net <= 0.0:
        return 0.0
    return _scale(p, net) * (net / move)


def chart_impact_curve(cfg, out, threshold_pct):
    imp = cfg["impact"]
    deadband = cfg.get("deadband_bps", 0.0) / 10_000.0
    moves = np.logspace(np.log10(1e-5), np.log10(0.20), 800)   # 0.001% → 20%
    fig, ax = plt.subplots(figsize=(11, 6.5))
    for c in COINS:
        y = np.array([_retained(imp[c], m, deadband) for m in moves]) * 100.0
        ax.plot(moves * 100.0, y, color=COL[c], lw=2.3, label=c)
    # anchor points computed directly from the deployed formula (with deadband)
    for mv in (0.0001, 0.001, 0.01, 0.05):
        for c in COINS:
            s = _retained(imp[c], mv, deadband) * 100.0
            ax.plot(mv * 100.0, s, "o", color=COL[c], ms=5, zorder=5)
            ax.annotate(f"{s:.1f}%", (mv * 100.0, s), textcoords="offset points",
                        xytext=(5, 5 if c == "BTC" else -12), fontsize=8,
                        color=COL[c], fontweight="bold")
    ax.axvline(deadband * 100.0, color="black", lw=1.5, ls="--",
               label=f"deadband ({cfg.get('deadband_bps', 0):.1f} bps = half CLOB spread)")
    ax.set_xscale("log")
    ax.set_xlim(0.001, 20.0)
    ax.set_ylim(0, 95)
    ax.xaxis.set_major_formatter(matplotlib.ticker.FuncFormatter(
        lambda v, _: f"{v:g}%"))
    ax.yaxis.set_major_formatter(matplotlib.ticker.PercentFormatter(decimals=0))
    ax.set_xlabel("Winning price move (%, log scale)")
    ax.set_ylabel("Share of raw gain the trader keeps")
    ax.set_title("Share of a winning trade kept after asymmetric impact + deadband\n"
                 f"base_rate {imp['BTC']['base_rate']:.0%}, rate_mult {imp['BTC']['rate_multiplier']:.0f}, "
                 f"ref ${imp['BTC']['reference_notional_usd']/1000:.0f}K, "
                 f"posMult BTC {imp['BTC']['position_multiplier']/1e6:,.3f}M / "
                 f"ETH {imp['ETH']['position_multiplier']/1e6:,.3f}M — 0 below the deadband",
                 fontsize=10)
    ax.legend(loc="best", framealpha=0.9)
    ax.grid(alpha=0.25, which="both")
    _save(fig, out, "08d_impact_curve.png")


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    base = Path(__file__).resolve().parent
    p.add_argument("--sim-dir", type=Path, default=base / "sim_flow_1.00")
    p.add_argument("--config", type=Path, default=base / "paper_config.yaml")
    p.add_argument("--charts-dir", type=Path, default=base / "charts")
    args = p.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(message)s")
    with open(args.config) as f:
        cfg = yaml.safe_load(f)
    args.charts_dir.mkdir(parents=True, exist_ok=True)

    trades, threshold_pct = load(args.sim_dir, cfg)
    liq = liq_rates(trades)
    logging.info("Per-coin charts from %s (%s trades, liq BTC %.1f%% / ETH %.1f%%):",
                 args.sim_dir.name, f"{len(trades):,}", liq["BTC"], liq["ETH"])

    chart_A(trades, args.charts_dir, liq)
    chart_B(trades, args.charts_dir, liq)
    chart_C(trades, args.charts_dir, liq)
    chart_D(trades, args.charts_dir, threshold_pct)
    chart_E(trades, args.charts_dir, liq)
    chart_F(trades, args.charts_dir, liq)
    chart_liq_by_coin(trades, args.charts_dir, liq)
    chart_impact_curve(cfg, args.charts_dir, threshold_pct)
    logging.info("Done → %s/", args.charts_dir)


if __name__ == "__main__":
    main()
